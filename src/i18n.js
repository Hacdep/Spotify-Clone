export function getInitialLocale() {
  try {
    const saved = localStorage.getItem("spotify-locale");
    if (supportedLocales.includes(saved)) return saved;
  } catch {
    // Storage can be unavailable in private browsing; use the device language.
  }

  const preferredLanguages = navigator.languages?.length
    ? navigator.languages
    : [navigator.language];

  for (const language of preferredLanguages) {
    const locale = language?.toLowerCase().split("-")[0];
    if (supportedLocales.includes(locale)) return locale;
  }

  return "en";
}

export function translate(locale, key, values = {}) {
  const template = messages[locale]?.[key] ?? messages.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => values[name] ?? "");
}
